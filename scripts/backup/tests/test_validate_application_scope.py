#!/usr/bin/env python3
"""Focused unit tests for application-scope restore inventory checks."""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[3]
VALIDATOR = ROOT / "scripts/backup/validate-application-scope.py"

DDL = """\
CREATE TABLE public.serial_ledger (id integer NOT NULL);
CREATE TABLE public.identity_default_ledger (id bigint NOT NULL);
CREATE TABLE public.identity_always_ledger (id bigint NOT NULL);
CREATE SEQUENCE public.serial_ledger_id_seq;
ALTER SEQUENCE public.serial_ledger_id_seq OWNED BY public.serial_ledger.id;
ALTER TABLE ONLY public.identity_default_ledger ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.identity_default_ledger_id_seq
);
ALTER TABLE ONLY public.identity_always_ledger ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY (
    SEQUENCE NAME public.identity_always_ledger_id_seq
);
"""


class ApplicationScopeSequenceValidationTests(unittest.TestCase):
    def run_validator(self, *args: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(VALIDATOR), *args], text=True, capture_output=True, check=False
        )

    def test_manifest_includes_explicit_and_identity_sequences(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            ddl = root / "public.sql"
            manifest = root / "manifest.json"
            ddl.write_text(DDL, encoding="utf-8")
            result = self.run_validator("--ddl", str(ddl), "--manifest", str(manifest))
            self.assertEqual(result.returncode, 0, result.stderr)
            sequences = json.loads(manifest.read_text(encoding="utf-8"))["sequences"]
            self.assertEqual(
                [item["name"] for item in sequences],
                [
                    "identity_always_ledger_id_seq",
                    "identity_default_ledger_id_seq",
                    "serial_ledger_id_seq",
                ],
            )
            self.assertEqual(sequences[0]["identity_type"], "a")
            self.assertEqual(sequences[1]["identity_type"], "d")
            self.assertEqual(sequences[2]["dependency_type"], "a")

    def test_inventory_and_state_mismatches_fail_closed(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            ddl = root / "public.sql"
            manifest = root / "manifest.json"
            inventory = root / "inventory.tsv"
            states = root / "states.sql"
            ddl.write_text(DDL, encoding="utf-8")
            self.assertEqual(self.run_validator("--ddl", str(ddl), "--manifest", str(manifest)).returncode, 0)
            inventory.write_text(
                "identity_always_ledger_id_seq\tidentity_always_ledger\tid\ti\ta\n"
                "identity_default_ledger_id_seq\tidentity_default_ledger\tid\ti\td\n",
                encoding="utf-8",
            )
            missing = self.run_validator("--manifest", str(manifest), "--actual-sequences", str(inventory))
            self.assertNotEqual(missing.returncode, 0)
            self.assertIn("serial_ledger_id_seq", missing.stderr)
            states.write_text(
                "SELECT pg_catalog.setval('public.identity_always_ledger_id_seq', 1, true);\n",
                encoding="utf-8",
            )
            state_mismatch = self.run_validator(
                "--manifest", str(manifest), "--sequence-states", str(states), "--emit-sequence-state-check"
            )
            self.assertNotEqual(state_mismatch.returncode, 0)
            self.assertIn("identity_default_ledger_id_seq", state_mismatch.stderr)


if __name__ == "__main__":
    unittest.main()
