create table if not exists import_reconciliations (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users(id) on delete cascade,
    account_id bigint not null references trading_accounts(id) on delete cascade,
    import_batch_id bigint not null unique references import_batches(id) on delete cascade,
    source varchar(30),
    trade_count integer not null,
    net_pnl numeric(18,2),
    status varchar(30) not null default 'NOT_REVIEWED',
    mismatch_reasons varchar(500),
    comment text,
    reviewed_at timestamp,
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint ck_import_reconciliations_status check (status in ('NOT_REVIEWED', 'MATCHED', 'MISMATCH_REPORTED'))
);
create index if not exists idx_import_reconciliations_user_account on import_reconciliations(user_id, account_id);

create table if not exists insight_feedback (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users(id) on delete cascade,
    account_id bigint not null references trading_accounts(id) on delete cascade,
    snapshot_id bigint not null references ai_leak_detector_snapshots(id) on delete cascade,
    finding_type varchar(80) not null,
    engine_version varchar(80) not null,
    rule_version varchar(80) not null,
    evidence_strength varchar(30) not null,
    helpful boolean not null,
    reason varchar(80),
    comment text,
    created_at timestamp not null,
    updated_at timestamp not null,
    constraint uk_insight_feedback_user_snapshot_finding unique (user_id, snapshot_id, finding_type)
);
create index if not exists idx_insight_feedback_quality on insight_feedback(finding_type, evidence_strength, engine_version, rule_version);
