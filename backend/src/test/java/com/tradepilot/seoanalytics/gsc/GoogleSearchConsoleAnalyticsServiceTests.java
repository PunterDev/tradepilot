package com.tradepilot.seoanalytics.gsc;

import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.namedparam.NamedParameterJdbcTemplate;

import java.sql.Connection;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.*;

class GoogleSearchConsoleAnalyticsServiceTests {
    private GoogleSearchConsoleClient client;
    private GoogleSearchConsoleAnalyticsService service;
    private NamedParameterJdbcTemplate jdbcTemplate;

    @BeforeEach
    void setUp() throws Exception {
        JdbcDataSource dataSource = new JdbcDataSource();
        dataSource.setURL("jdbc:h2:mem:gsc-" + System.nanoTime() + ";MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1");
        dataSource.setUser("sa");
        jdbcTemplate = new NamedParameterJdbcTemplate(dataSource);
        try (Connection connection = dataSource.getConnection()) {
            connection.createStatement().execute("""
                    create table users (
                      id bigint primary key,
                      role varchar(20) not null,
                      analytics_excluded boolean not null default false
                    )
                    """);
            connection.createStatement().execute("""
                    create table user_acquisition_attribution (
                      id bigint generated by default as identity primary key,
                      user_id bigint not null,
                      landing_page varchar(256) not null,
                      signup_completed_at timestamp not null,
                      first_import_completed_at timestamp,
                      first_insight_generated_at timestamp,
                      pro_converted_at timestamp
                    )
                    """);
        }
        client = mock(GoogleSearchConsoleClient.class);
        GoogleSearchConsoleProperties properties = enabledProperties();
        service = new GoogleSearchConsoleAnalyticsService(properties, client, new SearchConsolePageNormalizer(properties), jdbcTemplate);
    }

    @Test
    void disabledStateDoesNotCallGoogle() {
        GoogleSearchConsoleProperties disabled = new GoogleSearchConsoleProperties();
        var disabledService = new GoogleSearchConsoleAnalyticsService(disabled, client, new SearchConsolePageNormalizer(disabled), jdbcTemplate);

        var response = disabledService.dashboard(LocalDate.of(2026, 8, 1), LocalDate.of(2026, 8, 30));

        assertThat(response.enabled()).isFalse();
        assertThat(response.available()).isFalse();
        assertThat(response.error()).isEqualTo("Google Search Console is not connected.");
        verifyNoInteractions(client);
    }

    @Test
    void joinsSearchConsoleRowsToInternalLandingPageConversionsAndCachesResponse() {
        LocalDate start = LocalDate.of(2026, 8, 1);
        LocalDate end = LocalDate.of(2026, 8, 30);
        seedAttribution("/tools/revenge-trading-calculator", 20, 8, 2);
        mockSearchConsole(start, end);

        var response = service.dashboard(start, end);
        var cached = service.dashboard(start, end);

        assertThat(cached).isSameAs(response);
        assertThat(response.available()).isTrue();
        assertThat(response.summary().impressions()).isEqualTo(3000);
        assertThat(response.summary().clicks()).isEqualTo(150);
        assertThat(response.summary().ctr()).isEqualTo(5.0);
        assertThat(response.summary().nonBrandedClicks()).isEqualTo(140);
        assertThat(response.summary().brandedClicks()).isEqualTo(10);
        assertThat(response.pages()).hasSize(1);
        assertThat(response.pages().get(0).landingPage()).isEqualTo("/tools/revenge-trading-calculator");
        assertThat(response.pages().get(0).signupPerGscClick()).isEqualTo(14.29);
        assertThat(response.pages().get(0).activationPerGscClick()).isEqualTo(5.71);
        assertThat(response.pages().get(0).proPerGscClick()).isEqualTo(1.43);
        assertThat(response.queries()).extracting("searchIntent").contains("Non-Branded", "Branded");
        assertThat(response.queries()).filteredOn(row -> row.query().equals("revenge trading calculator")).first()
                .satisfies(row -> {
                    assertThat(row.landingPageSignups()).isEqualTo(20);
                    assertThat(row.activatedPer100Clicks()).isEqualTo(5.71);
                    assertThat(row.proPer100Clicks()).isEqualTo(1.43);
                });
        assertThat(response.trend().get(0).date()).isEqualTo(start);
        assertThat(response.opportunities()).extracting("category").contains("Striking Distance");
        verify(client, times(1)).query(SearchConsoleQueryType.PAGE, start, end);
        verify(client, times(1)).query(SearchConsoleQueryType.QUERY, start, end);
        verify(client, times(1)).query(SearchConsoleQueryType.QUERY_PAGE, start, end);
        verify(client, times(1)).query(SearchConsoleQueryType.DATE, start, end);
    }

    @Test
    void zeroClickRowsDoNotProduceNanOrInfinity() {
        LocalDate start = LocalDate.of(2026, 7, 1);
        LocalDate end = LocalDate.of(2026, 7, 31);
        when(client.query(eq(SearchConsoleQueryType.PAGE), eq(start), eq(end))).thenReturn(List.of(new SearchConsoleMetricRow(null, "https://tradepilotcoach.com/revenge-trading", null, 0, 100, 0, 12)));
        when(client.query(eq(SearchConsoleQueryType.QUERY), eq(start), eq(end))).thenReturn(List.of(new SearchConsoleMetricRow("revenge trading", null, null, 0, 100, 0, 12)));
        when(client.query(eq(SearchConsoleQueryType.QUERY_PAGE), eq(start), eq(end))).thenReturn(List.of(new SearchConsoleMetricRow("revenge trading", "https://tradepilotcoach.com/revenge-trading", null, 0, 100, 0, 12)));
        when(client.query(eq(SearchConsoleQueryType.DATE), eq(start), eq(end))).thenReturn(List.of());

        var response = service.dashboard(start, end);

        assertThat(response.pages().get(0).signupPerGscClick()).isZero();
        assertThat(response.queries().get(0).activatedPer100Clicks()).isZero();
    }

    @Test
    void excludesAdminAndAnalyticsExcludedConversionsFromSearchConsoleAttribution() {
        LocalDate start = LocalDate.of(2026, 8, 1);
        LocalDate end = LocalDate.of(2026, 8, 30);
        String landingPage = "/tools/revenge-trading-calculator";
        seedAttribution(landingPage, 1, 1, 1);
        seedAttribution(landingPage, 1, 1, 1, "ADMIN", false, 60_000L);
        seedAttribution(landingPage, 1, 1, 1, "USER", true, 70_000L);
        mockSearchConsole(start, end);

        var response = service.dashboard(start, end);

        assertThat(response.pages()).singleElement().satisfies(page -> {
            assertThat(page.signups()).isEqualTo(1);
            assertThat(page.firstInsights()).isEqualTo(1);
            assertThat(page.proConversions()).isEqualTo(1);
        });
    }

    @Test
    void apiFailureFallsBackToUnavailablePayload() {
        LocalDate start = LocalDate.of(2026, 6, 1);
        LocalDate end = LocalDate.of(2026, 6, 30);
        when(client.query(any(), eq(start), eq(end))).thenThrow(new SearchConsoleUnavailableException("raw google details"));

        var response = service.dashboard(start, end);

        assertThat(response.enabled()).isTrue();
        assertThat(response.available()).isFalse();
        assertThat(response.error()).isEqualTo("Search Console data is temporarily unavailable.");
        assertThat(response.error()).doesNotContain("google details");
    }

    private GoogleSearchConsoleProperties enabledProperties() {
        GoogleSearchConsoleProperties properties = new GoogleSearchConsoleProperties();
        properties.setEnabled(true);
        properties.setProperty("sc-domain:tradepilotcoach.com");
        properties.setServiceAccountJsonBase64("e30=");
        properties.setBrandTerms("tradepilot,trade pilot,tradepilotcoach");
        return properties;
    }

    private void mockSearchConsole(LocalDate start, LocalDate end) {
        when(client.query(eq(SearchConsoleQueryType.PAGE), eq(start), eq(end))).thenReturn(List.of(
                new SearchConsoleMetricRow(null, "https://tradepilotcoach.com/tools/revenge-trading-calculator?utm_source=x", null, 140, 2800, 0.05, 7.4),
                new SearchConsoleMetricRow(null, "https://example.com/not-tradepilot", null, 50, 1000, 0.05, 3)
        ));
        when(client.query(eq(SearchConsoleQueryType.QUERY), eq(start), eq(end))).thenReturn(List.of(
                new SearchConsoleMetricRow("revenge trading calculator", null, null, 140, 2800, 0.05, 7.4),
                new SearchConsoleMetricRow("tradepilot", null, null, 10, 200, 0.05, 1.2)
        ));
        when(client.query(eq(SearchConsoleQueryType.QUERY_PAGE), eq(start), eq(end))).thenReturn(List.of(
                new SearchConsoleMetricRow("revenge trading calculator", "https://www.tradepilotcoach.com/tools/revenge-trading-calculator/", null, 140, 2800, 0.05, 7.4),
                new SearchConsoleMetricRow("tradepilot", "https://tradepilotcoach.com/", null, 10, 200, 0.05, 1.2),
                new SearchConsoleMetricRow("external", "https://example.com/not-tradepilot", null, 100, 5000, 0.02, 8)
        ));
        when(client.query(eq(SearchConsoleQueryType.DATE), eq(start), eq(end))).thenReturn(List.of(
                new SearchConsoleMetricRow(null, null, start.toString(), 70, 1400, 0.05, 7.6),
                new SearchConsoleMetricRow(null, null, end.toString(), 70, 1400, 0.05, 7.2)
        ));
    }

    private void seedAttribution(String landingPage, int signups, int insights, int pro) {
        seedAttribution(landingPage, signups, insights, pro, "USER", false, 50_000L);
    }

    private void seedAttribution(String landingPage, int signups, int insights, int pro, String role, boolean analyticsExcluded, long firstUserId) {
        for (int i = 0; i < signups; i++) {
            long userId = firstUserId + i;
            jdbcTemplate.getJdbcTemplate().update(
                    "insert into users(id, role, analytics_excluded) values (?, ?, ?)",
                    userId,
                    role,
                    analyticsExcluded
            );
            jdbcTemplate.getJdbcTemplate().update("""
                    insert into user_acquisition_attribution
                    (user_id, landing_page, signup_completed_at, first_insight_generated_at, pro_converted_at)
                    values (?, ?, ?, ?, ?)
                    """,
                    userId,
                    landingPage,
                    LocalDateTime.of(2026, 8, 10, 12, 0),
                    i < insights ? LocalDateTime.of(2026, 8, 11, 12, 0) : null,
                    i < pro ? LocalDateTime.of(2026, 8, 12, 12, 0) : null
            );
        }
    }
}
